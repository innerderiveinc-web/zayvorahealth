"""
Multi-Factor Authentication (MFA) helpers for the ZAYVORA Identity service.

Implements TOTP (Time-based One-Time Password, RFC 6238) using the ``pyotp``
library.  Provides:

- ``generate_totp_secret()``    – cryptographically random base-32 secret.
- ``verify_totp()``             – validates a 6-digit code with clock skew tolerance.
- ``generate_qr_code_uri()``    – ``otpauth://`` URI suitable for QR-code display.

Usage example (enrollment flow)::

    from app.core.mfa import generate_totp_secret, generate_qr_code_uri, verify_totp

    # 1. Generate and store the secret (encrypted at rest!)
    secret = generate_totp_secret()
    user.mfa_secret_enc = encrypt(secret)

    # 2. Show the QR code to the user
    uri = generate_qr_code_uri(secret, email=user.email, issuer="ZAYVORA Health OS")

    # 3. Verify the user's first code before enabling MFA
    if not verify_totp(secret, code=form_data.code):
        raise HTTPException(422, "Invalid MFA code")

Dependencies:
    pip install pyotp
"""
from __future__ import annotations

import logging

logger = logging.getLogger("zayvora.identity.mfa")

try:
    import pyotp  # type: ignore[import]

    _PYOTP_AVAILABLE = True
except ImportError:  # pragma: no cover
    _PYOTP_AVAILABLE = False
    logger.warning(
        "pyotp is not installed – MFA helpers will raise RuntimeError. "
        "Install it with: pip install pyotp"
    )


def _require_pyotp() -> None:
    """Raise a clear error when pyotp is not installed."""
    if not _PYOTP_AVAILABLE:
        raise RuntimeError(
            "pyotp is required for MFA support. "
            "Add 'pyotp' to the service's requirements and reinstall."
        )


def generate_totp_secret() -> str:
    """Generate a cryptographically random base-32 TOTP secret.

    The returned string is 32 characters long (160 bits of entropy),
    which exceeds the RFC 4226 minimum of 128 bits.

    Returns:
        A base-32 encoded string suitable for storage and later use with
        ``verify_totp()`` and ``generate_qr_code_uri()``.

    Raises:
        RuntimeError: If ``pyotp`` is not installed.

    Example::

        secret = generate_totp_secret()
        # e.g. "JBSWY3DPEHPK3PXP..."
    """
    _require_pyotp()
    return pyotp.random_base32()


def verify_totp(secret: str, code: str) -> bool:
    """Validate a 6-digit TOTP code against *secret*.

    Accepts codes from the previous and next 30-second window (``valid_window=1``)
    to tolerate minor clock skew between the server and the authenticator app.

    Args:
        secret: Base-32 TOTP secret previously generated by
                ``generate_totp_secret()`` and stored (encrypted) on the user record.
        code:   The 6-digit numeric string supplied by the user.

    Returns:
        ``True`` if *code* is currently valid; ``False`` otherwise.

    Raises:
        RuntimeError: If ``pyotp`` is not installed.

    Example::

        if not verify_totp(user.mfa_secret, request_code):
            raise HTTPException(401, "Invalid MFA code")
    """
    _require_pyotp()
    if not code or not secret:
        return False
    totp = pyotp.TOTP(secret)
    return totp.verify(code, valid_window=1)


def generate_qr_code_uri(
    secret: str,
    *,
    email: str,
    issuer: str = "ZAYVORA Health OS",
) -> str:
    """Build the ``otpauth://totp/…`` URI for QR-code display.

    The returned URI follows the Key Uri Format specification
    (https://github.com/google/google-authenticator/wiki/Key-Uri-Format)
    and is compatible with Google Authenticator, Authy, 1Password, and any
    RFC 6238-compliant authenticator app.

    Args:
        secret: Base-32 TOTP secret returned by ``generate_totp_secret()``.
        email:  The user's email address (used as the account label inside the
                authenticator app).
        issuer: Human-readable service name shown in the authenticator app.
                Defaults to ``"ZAYVORA Health OS"``.

    Returns:
        A ``otpauth://`` URI string.  Pass this to a QR-code library
        (e.g. ``qrcode``) to render the enrollment QR code.

    Raises:
        RuntimeError: If ``pyotp`` is not installed.

    Example::

        uri = generate_qr_code_uri(secret, email="alice@example.com")
        # otpauth://totp/ZAYVORA%20Health%20OS%3Aalice%40example.com?...
    """
    _require_pyotp()
    totp = pyotp.TOTP(secret)
    return totp.provisioning_uri(name=email, issuer_name=issuer)
